source("flock_map.R")
set.seed(42)
map <- flock_map(d=2)
A <- cbind(rnorm(120,0,0.8),rnorm(120,0,0.7))
B <- cbind(rnorm(100,0.25,0.8),rnorm(100,0.2,0.7))
C <- cbind(rnorm(100,7,0.8),rnorm(100,7,0.7))
map <- flock_add(map,A,"A")
map <- flock_add(map,B,"B")
map <- flock_add(map,C,"C")
cat("Before:\n"); print(flock_map_table(map))
cat("A vs B:\n"); print(flock_pair_metrics(map,"A","B"))
cat("A vs C:\n"); print(flock_pair_metrics(map,"A","C"))
out <- flock_merge(map,"A","B",new_id="AB",max_mahalanobis=1.5,max_symmetric_kl=1)
stopifnot(out$merged, length(out$map$regions)==2L,
          out$map$regions$AB$n==220L)
map <- out$map
out2 <- flock_merge(map,"AB","C")
stopifnot(!out2$merged)
cat("After:\n"); print(flock_map_table(map))
pdf("flock_map_demo.pdf",width=7,height=5)
flock_plot(map)
dev.off()
cat("Saved flock_map_demo.pdf\n")
